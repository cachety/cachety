/**
 * Accord du nom avec le nombre (règle simplifiée) :
 * 1 et 2 ont leur propre forme (singulier, duel), 3 à 10 le pluriel,
 * 11 à 99 le singulier à l'accusatif, 100, 200… (et 0) le singulier.
 */
const count = (n: number, one: string, two: string, few: string, many: string, hundreds = many) => {
  if (n === 1) return one;
  if (n === 2) return two;
  const r = n % 100;
  if (r >= 3 && r <= 10) return `${n} ${few}`;
  if (r >= 11) return `${n} ${many}`;
  return `${n} ${hundreds}`;
};

