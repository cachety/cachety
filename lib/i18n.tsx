/** Le filigrane d'exemple EST la formule : motif, destinataire, date. */
export const exampleStamp = (t: Strings) => t.about.what.map((w) => w.part).join(", ");

// Exportée pour les tests. La valeur stockée est validée : un "lang" altéré
// dans localStorage (ex. "xx") rendrait STRINGS[lang] indéfini et planterait
// tout composant lisant t.* — on retombe alors sur la détection navigateur.
export function detectLang(saved: string | null, navLang: string): Lang {
  if (saved !== null && isLang(saved)) return saved;
  const nav = navLang.toLowerCase();
  if (nav.startsWith("fr")) return "fr";
  if (nav.startsWith("ja")) return "ja";
  if (nav.startsWith("zh")) return "zh";
  if (nav.startsWith("es")) return "es";
  if (nav.startsWith("ar")) return "ar";
  if (nav.startsWith("fa")) return "fa";
  if (nav.startsWith("de")) return "de";
  if (nav.startsWith("pt")) return "pt";
  // « in » : ancien code de l'indonésien, encore renvoyé par certains Android.
  if (nav.startsWith("id") || nav.startsWith("in")) return "id";
  if (nav.startsWith("nl")) return "nl";
  return "en";
}

/** BCP 47 pour <html lang> : le chinois simplifié a besoin de zh-CN pour les glyphes. */
export function htmlLang(lang: Lang): string {
  return HREFLANG[lang];
}

/**
 * Polices CJK (scripts/fonts.mjs) : la feuille n'est liée qu'en japonais ou
 * en chinois. React la place dans <head> (prérendu compris) et ne la charge
 * qu'une fois.
 */
const CJK_FONT_CSS: Partial<Record<Lang, string>> = {
  ja: "/fonts/noto-sans-jp/index.css",
  zh: "/fonts/noto-sans-sc/index.css",
};

const LangContext = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: Strings;
}>({ lang: "en", setLang: () => {}, t: STRINGS.en });

/** Accueil : la racine ou une page de langue (/fr, /ja…). */
function isHomePath() {
  const path = window.location.pathname.replace(/\/+$/, "") || "/";
  return path === "/" || isLang(path.slice(1));
}

/** Adresse de l'accueil dans une langue, sans rechargement ; garde « ?… » et « #… » (pré-remplissage, partage). */
function goHome(l: Lang) {
  window.history.replaceState(null, "", SITE_META[l].path + window.location.search + window.location.hash);
}

export function LangProvider({
  children,
  forcedLang,
}: {
  children: React.ReactNode;
  forcedLang?: Lang;
}) {
  // Une URL /fr, /en, /ja… impose sa langue (liens partageables) ;
  // la racine garde la détection préférence enregistrée → navigateur.
  const [lang, setLangState] = useState<Lang>(forcedLang ?? "en");

  useEffect(() => {
    if (forcedLang) {
      writePref("lang", forcedLang);
      return;
    }
    const detected = detectLang(readPref("lang"), navigator.language);
    setLangState(detected);
    // Racine affichée dans une autre langue que l'anglais : l'adresse devient
    // celle de la langue (/fr…), sans rechargement, pour qu'un lien copié ou
    // partagé ouvre la bonne langue et en montre le bon aperçu. Les robots,
    // sans préférence, gardent la racine anglaise (x-default).
    if (detected !== "en" && isHomePath()) goHome(detected);
  }, [forcedLang]);

  useEffect(() => {
    document.documentElement.lang = htmlLang(lang);
    document.documentElement.dir = dirOf(lang);
    // Sur l'accueil, l'onglet et la description suivent la langue affichée.
    if (isHomePath()) {
      document.title = SITE_META[lang].title;
      document.querySelector('meta[name="description"]')?.setAttribute("content", SITE_META[lang].description);
    }
  }, [lang]);

  const setLang = (l: Lang) => {
    writePref("lang", l);
    setLangState(l);
    // Sur l'accueil, l'URL reflète la langue affichée : l'adresse reste
    // partageable telle quelle. replaceState évite de démonter l'app
    // (les documents chargés seraient perdus avec une vraie navigation).
    if (isHomePath()) goHome(l);
  };

  return (
    <LangContext.Provider value={{ lang, setLang, t: STRINGS[lang] }}>
      {CJK_FONT_CSS[lang] && <link rel="stylesheet" href={CJK_FONT_CSS[lang]} precedence="fonts" />}
      {children}
    </LangContext.Provider>
  );
}

export const useLang = () => useContext(LangContext);
export const useT = () => useContext(LangContext).t;
